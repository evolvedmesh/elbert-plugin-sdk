// Writes bin/lucide-names.ts - every Lucide icon name Elbert knows - from the
// host's own table, so `check` refuses an icon Elbert would refuse at install.
// Run it after Elbert upgrades lucide_icons_flutter:
//
//   bun scripts/gen-lucide-names.ts [path/to/elbert/lib/plugins/ui/lucide_icon_table.dart]

import fs from 'node:fs';
import path from 'node:path';

const table = process.argv[2] ?? path.join(import.meta.dir, '..', '..', 'elbert', 'lib', 'plugins', 'ui', 'lucide_icon_table.dart');
const source = fs.readFileSync(table, 'utf8');
const names = [...source.matchAll(/^\s*'([a-z0-9-]+)':\s*LucideIcons\./gm)].map((m) => m[1]);
if (names.length < 1000) throw new Error(`Found only ${names.length} icon names in ${table}`);
const header = source.match(/^\/\/ Source: (.*)$/m)?.[1] ?? 'lucide_icons_flutter';

const out = `// GENERATED by scripts/gen-lucide-names.ts from Elbert's lucide_icon_table.dart (${header}).
// Do not edit by hand.

/** Every Lucide icon name Elbert can draw. */
export const LUCIDE_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(names)});
`;
const target = path.join(import.meta.dir, '..', 'bin', 'lucide-names.ts');
fs.writeFileSync(target, out);
// In the repo's own style, so `bun run check` (biome) passes on it.
Bun.spawnSync(['bunx', 'biome', 'format', '--write', target], { cwd: path.join(import.meta.dir, '..') });
console.log(`bin/lucide-names.ts: ${names.length} icons`);
